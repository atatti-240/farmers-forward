TABLES = ("admins", "otps", "farms", "samples", "results", "contacts")


def schema() -> str:
    """The CREATE TABLE script for the active backend."""
    return SCHEMA_POSTGRES if using_postgres() else SCHEMA_SQLITE


def _is_admin_table(statement: str) -> bool:
    return bool(re.match(r"CREATE TABLE IF NOT EXISTS (admins|otps)\b", statement))


def _schema_statements(admin_tables: bool) -> List[str]:
    """The active backend's CREATE TABLEs for the login tables, or for the rest."""
    return [s for s in _statements(schema()) if _is_admin_table(s) == admin_tables]


def _statements(script: str) -> List[str]:
    """Split a schema script into single statements.

    The scripts above contain no string literal with a ';' in it, so a plain
    split is exact. One statement at a time is what lets init_db() run the
    whole script inside its own transaction: sqlite3's executescript() always
    COMMITs first.
    """
    return [part.strip() for part in script.split(";") if part.strip()]


# ---------------------------------------------------------------------------
# SQL translation
# ---------------------------------------------------------------------------
_INSERT_RE = re.compile(r"^\s*INSERT\b", re.IGNORECASE)
_RETURNING_RE = re.compile(r"\bRETURNING\b", re.IGNORECASE)


def to_postgres_sql(sql: str) -> str:
    """Rewrite a `?`-placeholder statement for psycopg2.

    Every literal `%` is doubled, including inside a quoted string: psycopg2
    interpolates across the whole statement, not just outside literals. `?` is
    translated only outside a literal, so a real question mark in text survives.
    """
    out = []
    in_string = False
    index = 0
    while index < len(sql):
        char = sql[index]
        if char == "'":
            # '' inside a string literal is an escaped quote, not a terminator.
            if in_string and index + 1 < len(sql) and sql[index + 1] == "'":
                out.append("''")
                index += 2
                continue
            in_string = not in_string
            out.append(char)
        elif char == "%":
            out.append("%%")
        elif char == "?":
            out.append("%s" if not in_string else "?")
        else:
            out.append(char)
        index += 1
    return "".join(out)


def _with_returning_id(sql: str):
    """Append RETURNING id to an INSERT so lastrowid has something to report.

    Returns (statement, returns_id).
    """
    if not _INSERT_RE.match(sql) or _RETURNING_RE.search(sql):
        return sql, False
    return sql.rstrip().rstrip(";") + " RETURNING id", True


# ---------------------------------------------------------------------------
# Connection wrapper
# ---------------------------------------------------------------------------
class _PostgresCursor:
    """A psycopg2 cursor presenting the two attributes sqlite3 callers use."""

    def __init__(self, cursor, lastrowid):
        self._cursor = cursor
        self.lastrowid = lastrowid
        self.rowcount = cursor.rowcount

    def fetchone(self):
        try:
            return self._cursor.fetchone()
        except _driver().ProgrammingError:
            # Statement returned no result set (an UPDATE, say).
            return None

    def fetchall(self):
        try:
            return self._cursor.fetchall()
        except _driver().ProgrammingError:
            return []


class _PostgresConnection:
    """Gives a psycopg2 connection the sqlite3 surface the callers expect."""

    def __init__(self, conn):
        self._conn = conn

    def execute(self, sql: str, params: Iterable[Any] = ()):
        params = tuple(params)
        statement, wants_id = _with_returning_id(sql)
        cursor = self._conn.cursor(cursor_factory=_driver().extras.DictCursor)
        if params:
            cursor.execute(to_postgres_sql(statement), params)
        else:
            # No parameters means no interpolation, so `%` must stay literal.
            cursor.execute(statement)
        lastrowid = None
        if wants_id:
            row = cursor.fetchone()
            lastrowid = row[0] if row else None
        return _PostgresCursor(cursor, lastrowid)

    def executescript(self, script: str):
        with self._conn.cursor() as cursor:
            cursor.execute(script)
        self._conn.commit()

    def commit(self):
        self._conn.commit()

    def rollback(self):
        self._conn.rollback()

    def close(self):
        self._conn.close()

    def __enter__(self):
        return self

    def __exit__(self, exc_type, exc, tb):
        # Matches sqlite3: commit on success, roll back on error, stay open.
        if exc_type is None:
            self._conn.commit()
        else:
            self._conn.rollback()
        return False


def _postgres_dsn() -> str:
    """The configured URL, with SSL required unless the caller said otherwise.

    Supabase terminates TLS and psycopg2 defaults to sslmode=prefer, which will
    silently fall back to plaintext if the handshake fails.
    """
    url = config.DATABASE_URL
    if "sslmode=" in url:
        return url
    return url + ("&" if "?" in url else "?") + "sslmode=require"


def get_db():
    """Open a connection to the active backend.

    Callers close it themselves, as before. On Postgres this is a new pooled
    connection per call, which is why the Supabase transaction pooler (port
    6543) is the documented endpoint: gunicorn's sync workers would otherwise
    exhaust the direct-connection cap.
    """
    if using_postgres():
        return _PostgresConnection(_driver().connect(_postgres_dsn()))
    conn = sqlite3.connect(config.DATABASE_PATH)
    conn.row_factory = sqlite3.Row
    conn.execute("PRAGMA foreign_keys = ON")
    return conn


def integrity_error():
    """The active driver's IntegrityError, for `except` clauses."""
    return _driver().IntegrityError if using_postgres() else sqlite3.IntegrityError


# Created by the one-time multi-admin migration; kept so the previous deploy can
# be restored, and never read by the app.
LEGACY_TABLES = ("admins_legacy",)

# Indexes come after the migration below: on a database that still has the old
# otps table, its `email` column does not exist yet. The created_at index serves
# the prune and the global rate limit, which run on every login request.
INDEXES = """
CREATE INDEX IF NOT EXISTS otps_email_created_idx ON otps (email, created_at);
CREATE INDEX IF NOT EXISTS otps_created_idx ON otps (created_at);
"""

# Key for the Postgres advisory lock init_db() holds. Every gunicorn worker
# boots at once, and the one-time admins migration must run exactly once. The
# lock is transaction-scoped, which is what keeps it correct behind Supabase's
# transaction-mode pooler: it can neither outlive the transaction nor leak to
# whichever client gets the server connection next.
_INIT_LOCK_KEY = 0x46460003

# Columns only the pre-multi-admin `admins` table had. Their presence is what
# marks a database that still needs _migrate_legacy_admins().
_LEGACY_ADMIN_COLUMNS = frozenset(("username", "password_hash"))

# Every table, which Supabase's auto-generated REST API must never serve: the
# login tables hold codes and emails, contacts holds visitors' details.
_RLS_TABLES = TABLES + LEGACY_TABLES

# The address the old config filled in when DEFAULT_ADMIN_EMAIL was unset. It
# may or may not be a real inbox (farmersforward.org is the production domain,
# and the old code emailed codes there), so the migration keeps it unless
# DEFAULT_ADMIN_EMAIL names another one -- dropping it could leave no owner.
OLD_DEFAULT_EMAIL = "admin@farmersforward.org"


class LegacySchemaError(RuntimeError):
    """The database still has the pre-multi-admin admins table.

    Raised by init_db(migrate=False): only the app's own boot performs the
    one-time migration, so a CLI pointed at production from a newer checkout
    can't rewrite the schema under the deploy that is still serving it.
    """


def init_db(migrate: bool = True) -> None:
    """Create all tables if they do not already exist. Safe on every boot.

    Everything -- the CREATE TABLEs, the crop_type upgrade, the one-time
    multi-admin migration -- runs in ONE transaction that only one process can
    hold at a time (a Postgres advisory lock; BEGIN IMMEDIATE on SQLite). A boot
    that dies part-way therefore changes nothing, and workers booting together
    queue up instead of racing. Once a database is up to date, a run is a no-op.

    With migrate=False a database that still needs the migration raises
    LegacySchemaError before anything is written; the CLI scripts use that.
    """
    migrated = None
    conn = get_db()
    try:
        if using_postgres():
            conn.execute("SELECT pg_advisory_xact_lock(?)", (_INIT_LOCK_KEY,))
        else:
            conn.execute("BEGIN IMMEDIATE")
        if not migrate and _needs_admin_migration(conn):
            raise LegacySchemaError(
                "the database still has the old single-admin schema. The first "
                "boot of this version of the app migrates it; this command "
                "won't, so the deploy still serving that schema keeps working.")
        for statement in _schema_statements(admin_tables=False):
            conn.execute(statement)
        _add_crop_type(conn)
        # Before the admin CREATE TABLEs: on a database that still has the old
        # admins table they would be no-ops, and the new otps table can't
        # reference an integer admins.id anyway.
        migrated = _migrate_legacy_admins(conn)
        for statement in _schema_statements(admin_tables=True):
            conn.execute(statement)
        for statement in _statements(INDEXES):
            # CREATE INDEX IF NOT EXISTS still takes a SHARE lock on the table,
            # so an index that exists is skipped (no lock on a normal boot).
            name = re.match(r"CREATE INDEX (?:IF NOT EXISTS )?(\w+)", statement).group(1)
            if not using_postgres() or not _relation_exists(conn, name):
                conn.execute(statement)
        if using_postgres():
            _enable_row_level_security(conn)
        conn.commit()
    except Exception:
        conn.rollback()
        raise
    finally:
        conn.close()
    # Only after COMMIT, so the log can never claim a migration that rolled back.
    if migrated is not None:
        count, owner = migrated
        print("[admin-auth] migrated %d legacy admin row(s) into the new admins "
              "table (owner: %s); the old table is kept as admins_legacy"
              % (count, mask_email(owner) if owner else "none"), flush=True)


def admins_shape(conn) -> str:
    """'current', 'legacy' or 'missing': the shape of the admins table. Read-only.

    'legacy' is the single-admin table from before multi-admin profiles, which
    init_db(migrate=True) migrates. The CLI scripts use this to explain a
    database instead of touching it.
    """
    columns = _columns(conn, "admins")
    if not columns:
        return "missing"
    return "legacy" if columns & _LEGACY_ADMIN_COLUMNS else "current"


def needs_admin_migration() -> bool:
    """True if the database still has the pre-multi-admin admins table. Read-only."""
    conn = get_db()
    try:
        return _needs_admin_migration(conn)
    finally:
        conn.close()


def _needs_admin_migration(conn) -> bool:
    return admins_shape(conn) == "legacy"


def _add_crop_type(conn) -> None:
    """Existing readings have no recorded crop; preserve that missingness.

    New submissions require a crop in the API, while old reports stay valid.
    Checked first, because even a no-op ALTER takes an ACCESS EXCLUSIVE lock,
    held to the end of init_db()'s transaction: every boot would stall the
    live deploy's queries on samples.
    """
    if "crop_type" in _columns(conn, "samples"):
        return
    if using_postgres():
        conn.execute("ALTER TABLE samples ADD COLUMN IF NOT EXISTS crop_type TEXT")
    else:
        conn.execute("ALTER TABLE samples ADD COLUMN crop_type TEXT")


def _columns(conn, table: str) -> set:
    """Column names of `table` (empty if it doesn't exist).

    `table` is always a constant from this module; SQLite can't take a
    PRAGMA argument as a parameter.
    """
    if using_postgres():
        rows = conn.execute(
            "SELECT column_name FROM information_schema.columns "
            "WHERE table_schema = current_schema() AND table_name = ?", (table,)).fetchall()
        return {row[0] for row in rows}
    return {row["name"] for row in conn.execute("PRAGMA table_info(%s)" % table).fetchall()}


def _relation_exists(conn, name: str) -> bool:
    """Postgres: whether a table or index called `name` exists."""
    row = conn.execute("SELECT to_regclass(?)", (name,)).fetchone()
    return row is not None and row[0] is not None


def _table_exists(conn, table: str) -> bool:
    if using_postgres():
        row = conn.execute(
            "SELECT 1 FROM information_schema.tables "
            "WHERE table_schema = current_schema() AND table_name = ?", (table,)).fetchone()
    else:
        row = conn.execute(
            "SELECT 1 FROM sqlite_master WHERE type = 'table' AND name = ?", (table,)).fetchone()
    return row is not None


def _migrate_legacy_admins(conn) -> int:
    """One-time move from the single-admin table to multi-admin profiles.

    Until roadmap #3, `admins` held one row (integer id, username,
    password_hash, phone, email) and login was username + password + emailed
    code. Admins are now identified by email, keyed by uuid, and sign in with
    the emailed code alone. When `admins` still has the old shape:

      1. it is renamed to admins_legacy and left untouched, so the previous
         deploy can be restored (rollback SQL in README.md);
      2. otps is dropped -- its rows are login codes that expire within
         minutes -- and both tables are recreated in their new shape;
      3. the legacy rows are copied across: the oldest becomes the owner,
         emails are normalized, created_at is kept. The owner's display name
         is DEFAULT_ADMIN_NAME if set (and storable), else the old username.
         When DEFAULT_ADMIN_EMAIL is a valid address it replaces the owner's
         legacy email if that is missing, malformed, or the old built-in
         default (OLD_DEFAULT_EMAIL). The owner is never dropped for keeping
         the old default; only a row with no usable email at all is skipped
         (it stays in admins_legacy).

    Runs inside init_db()'s transaction and lock. On every later boot
    `admins` has no username column any more, and this returns None without
    touching anything. Otherwise returns (admins migrated, owner email); the
    caller logs it once the transaction has committed.
    """
    if not _needs_admin_migration(conn):
        return None
    if _table_exists(conn, "admins_legacy"):
        raise RuntimeError(
            "admins still has the old single-admin shape, but admins_legacy "
            "already exists, so the one-time migration has nowhere to keep the "
            "old table. Inspect both and rename or drop one by hand.")

    legacy = conn.execute(
        "SELECT id, username, email, created_at FROM admins ORDER BY id").fetchall()
    if using_postgres():
        _rename_legacy_indexes(conn)
        _free_parked_constraint_names(conn)
    conn.execute("ALTER TABLE admins RENAME TO admins_legacy")
    conn.execute("DROP TABLE IF EXISTS otps")
    for statement in _schema_statements(admin_tables=True):
        conn.execute(statement)

    migrated = []
    for row in legacy:
        owner = not migrated
        email = normalize_email(row["email"])
        chosen = normalize_email(config.DEFAULT_ADMIN_EMAIL) if owner else ""
        if is_valid_email(chosen) and (not is_valid_email(email) or email == OLD_DEFAULT_EMAIL):
            email = chosen
        if not is_valid_email(email) or email in migrated:
            print("[admin-auth] WARNING: legacy admin %r has no usable email (or "
                  "shares one) and was NOT migrated; the row stays in "
                  "admins_legacy." % row["username"], flush=True)
            continue
        if owner and email == OLD_DEFAULT_EMAIL:
            print("[admin-auth] WARNING: the owner keeps the old default address %s. "
                  "If that inbox doesn't receive mail, set DEFAULT_ADMIN_EMAIL before "
                  "the first boot, or afterwards run "
                  "python3 -m backend.reset_admin --email you@example.com"
                  % OLD_DEFAULT_EMAIL, flush=True)
        name = ((config.DEFAULT_ADMIN_NAME or "").strip() if owner else "") or row["username"]
        if len(name) > 100 or has_control_chars(name):
            name = str(row["username"])[:100]
        conn.execute(
            "INSERT INTO admins (id, email, display_name, role, is_active, created_at) "
            "VALUES (?, ?, ?, ?, ?, ?)",
            (new_id(), email, name, "owner" if owner else "admin", True,
             row["created_at"] or now_iso()))
        migrated.append(email)
    return len(migrated), (migrated[0] if migrated else None)


def _rename_legacy_indexes(conn) -> None:
    """Move the legacy table's index names out of the new table's way.

    Index names are unique per schema and a table rename keeps them, so the new
    table's primary key would otherwise come out as admins_pkey1. Only indexes
    that belong to the table being migrated are renamed, and only onto a free
    name: after a rollback, admins_pkey may belong to the parked new table and
    admins_legacy_pkey may already exist. Renaming an index that backs a
    constraint renames the constraint too.
    """
    rows = conn.execute(
        "SELECT c.relname FROM pg_index i JOIN pg_class c ON c.oid = i.indexrelid "
        "WHERE i.indrelid = 'admins'::regclass").fetchall()
    for (name,) in [tuple(row) for row in rows]:
        if name not in ("admins_pkey", "admins_username_key"):
            continue
        target = "admins_legacy_" + name[len("admins_"):]
        taken = conn.execute("SELECT to_regclass(?)", (target,)).fetchone()
        if taken is None or taken[0] is None:
            # Both names come from the fixed list above, never from input.
            conn.execute("ALTER INDEX %s RENAME TO %s" % (name, target))


def _free_parked_constraint_names(conn) -> None:
    """Give the new admins table its plain constraint names after a rollback.

    The rollback runbook parks the new table under a name the operator picks,
    and it keeps its constraint names (admins_pkey, admins_email_key,
    admins_email_check). Postgres keeps those unique per schema, so a redeploy
    would create admins_pkey1 and friends, and that one database would differ
    from every other. Renaming the parked table's constraints after the table
    avoids it; RENAME CONSTRAINT renames a backing index too.
    """
    rows = conn.execute(
        "SELECT con.conname, rel.relname FROM pg_constraint con "
        "JOIN pg_class rel ON rel.oid = con.conrelid "
        "JOIN pg_namespace n ON n.oid = rel.relnamespace "
        "WHERE n.nspname = current_schema() AND rel.relname <> 'admins' "
        "AND con.conname IN ('admins_pkey', 'admins_email_key', 'admins_email_check')"
    ).fetchall()
    for conname, relname in [tuple(row) for row in rows]:
        target = relname + conname[len("admins"):]
        clash = conn.execute(
            "SELECT 1 FROM pg_constraint con JOIN pg_namespace n ON n.oid = con.connamespace "
            "WHERE n.nspname = current_schema() AND con.conname = ?", (target,)).fetchone()
        taken = conn.execute("SELECT to_regclass(?)", (target,)).fetchone()
        if clash is None and (taken is None or taken[0] is None):
            # relname and conname come from the catalog, filtered to the fixed
            # names above; quote_ident-style quoting keeps any table name valid.
            conn.execute('ALTER TABLE "%s" RENAME CONSTRAINT "%s" TO "%s"'
                         % (relname.replace('"', '""'), conname, target.replace('"', '""')))


def _enable_row_level_security(conn) -> None:
    """Close every table to Supabase's auto-generated REST API.

    Supabase grants its anon and authenticated roles access to every table in
    the public schema, so anyone holding the project's anon key could read
    (and write) them over HTTPS: otps with its live login codes, admins,
    contacts with visitors' names and emails, all the field data. Row-level
    security with no policies turns that into zero rows. The app connects as
    the tables' owner, which RLS does not apply to, so nothing here changes
    for it. Only tables without RLS are altered, so a normal boot takes no lock.

    Best-effort: a role that may not ALTER a table logs a warning instead of
    failing the boot (the savepoint keeps the rest of init_db's transaction).
    """
    rows = conn.execute(
        "SELECT c.relname FROM pg_class c JOIN pg_namespace n ON n.oid = c.relnamespace "
        "WHERE n.nspname = current_schema() AND c.relkind = 'r' "
        "AND NOT c.relrowsecurity AND c.relname IN (%s)"
        % ", ".join("?" * len(_RLS_TABLES)), _RLS_TABLES).fetchall()
    for (table,) in [tuple(row) for row in rows]:
        conn.execute("SAVEPOINT ff_enable_rls")
        try:
            # The name comes from pg_class, filtered to the constants above.
            conn.execute("ALTER TABLE %s ENABLE ROW LEVEL SECURITY" % table)
            conn.execute("RELEASE SAVEPOINT ff_enable_rls")
        except _driver().Error as exc:
            conn.execute("ROLLBACK TO SAVEPOINT ff_enable_rls")
            print("[admin-auth] WARNING: could not enable row-level security on %s "
                  "(%s). Enable it in the Supabase dashboard." % (table, exc), flush=True)


def new_id() -> str:
    """A new random uuid, as the canonical string both backends store."""
    return str(uuid.uuid4())


def normalize_email(value) -> str:
    """How an email is stored and looked up: trimmed and lowercased.

    The admins table enforces the lowercase part (CHECK email = lower(email)),
    so every lookup and insert must go through this. Non-strings become ''.
    """
    if not isinstance(value, str):
        return ""
    return value.strip().lower()


# \s also matches \r and \n, so a valid address can't smuggle a header line.
EMAIL_RE = re.compile(r"^[^@\s]+@[^@\s]+\.[^@\s]+$")
MAX_EMAIL_LENGTH = 254


# Bidirectional embedding/override/isolate controls: they can make a name render
# as something else ("Logged in as" a spoofed string).
_BIDI_CONTROLS = frozenset(chr(code) for code in (*range(0x202A, 0x202F),
                                                  *range(0x2066, 0x206A)))


def has_control_chars(text: str) -> bool:
    """C0 and C1 control characters, DEL, and bidi overrides."""
    return any(ord(char) < 32 or 127 <= ord(char) <= 159 or char in _BIDI_CONTROLS
               for char in text)


def is_valid_email(email) -> bool:
    """True for a normalized address plausible enough to send a code to.

    Lives here, next to normalize_email(), because init_db()'s migration needs
    it and database.py can't import auth.
    """
    return (isinstance(email, str) and bool(email) and len(email) <= MAX_EMAIL_LENGTH
            and not has_control_chars(email) and bool(EMAIL_RE.match(email)))


def mask_email(value) -> str:
    """Enough of an address to recognize it in a log line, not to reuse it."""
    local, at, domain = str(value or "").partition("@")
    if not at:
        return "***"
    return "%s***@%s" % (local[:2], domain)


def now_iso() -> str:
    """Current time as an ISO8601 UTC string."""
    return datetime.now(timezone.utc).isoformat()


